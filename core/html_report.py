import os
import pandas as pd


def generate_html_report(output_dir, metrics={}, has_compare=False, has_csv=False):
    """生成完整HTML报告"""
    html = f"""
    <!DOCTYPE html>
    <html lang="zh-CN">
    <head>
        <meta charset="UTF-8">
        <title>YOLO 检测结果报告</title>
        <style>
            body {{font-family: Arial; padding:20px; background:#f5f5f5;}}
            .card {{background:white; padding:20px; border-radius:10px; margin:20px 0; box-shadow:0 2px 5px rgba(0,0,0,0.1);}}
            img {{max-width:100%; height:auto; border-radius:8px; margin:10px 0;}}
            .grid {{display:grid; grid-template-columns:1fr 1fr; gap:20px;}}
            table {{width:100%; border-collapse:collapse; margin:10px 0;}}
            th,td {{border:1px solid #ddd; padding:8px; text-align:center;}}
            th {{background:#007bff; color:white;}}
        </style>
    </head>
    <body>
        <h1>🚀 YOLO Result Visualizer 检测报告</h1>

        <div class="card">
            <h2>📊 训练核心指标</h2>
            <table>
                <tr><th>最佳Epoch</th><th>最终Epoch</th><th>mAP50</th><th>mAP50-95</th><th>最终训练损失</th><th>最终验证损失</th></tr>
                <tr>
                    <td>{metrics.get('best_epoch', '-')}</td>
                    <td>{metrics.get('last_epoch', '-')}</td>
                    <td>{metrics.get('mAP50', '-')}</td>
                    <td>{metrics.get('mAP50-95', '-')}</td>
                    <td>{metrics.get('final_train_loss', '-')}</td>
                    <td>{metrics.get('final_val_loss', '-')}</td>
                </tr>
            </table>
        </div>
    """

    # 损失3D图
    if has_csv and os.path.exists(os.path.join(output_dir, "loss_3d.png")):
        html += f'''
        <div class="card">
            <h2>📈 损失函数3D趋势图</h2>
            <img src="loss_3d.png" alt="3D Loss">
        </div>
        '''

    # 对比图
    if has_compare:
        compare_dir = os.path.join(output_dir, "comparisons")
        imgs = [f for f in os.listdir(compare_dir) if f.endswith(('jpg', 'png'))]
        if imgs:
            html += '<div class="card"><h2>🎯 真值 VS 预测 对比</h2><div class="grid">'
            for img in imgs[:8]: html += f'<img src="comparisons/{img}" alt="对比图">'
            html += '</div></div>'

    # 统计图表
    stats_dir = os.path.join(output_dir, "stats")
    if os.path.exists(stats_dir):
        html += '<div class="card"><h2>📦 类别统计图表</h2><div class="grid">'
        for f in ["class_dist.png", "count_dist.png"]:
            if os.path.exists(os.path.join(stats_dir, f)):
                html += f'<img src="stats/{f}" alt="统计图表">'
        html += '</div></div>'

    html += """
    <div class="card" style="text-align:center; color:#666;">
        <p>Generated by yolo-result-visualizer | 纯本地运行 · 安全隐私</p>
    </div>
    </body></html>
    """

    with open(os.path.join(output_dir, "report.html"), "w", encoding="utf-8") as f:
        f.write(html)
    print("✅ HTML报告已生成：outputs/report.html")